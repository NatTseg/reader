// Packs data/katameros-raw.json into katameros-data.js: identical reading sets are stored once.
// Usage: node scripts/build_katameros.mjs [data/katameros-raw.json] [katameros-data.js]
import fs from "node:fs";
const [input = "data/katameros-raw.json", output = "katameros-data.js"] = process.argv.slice(2);
const raw = JSON.parse(fs.readFileSync(input, "utf8"));
// The API returns no verses for two citations its English Bible lacks; restore them from the Katameros source refs.
function fixReference(p) {
  const range = (a, b) => Array.from({length: b - a + 1}, (_, i) => a + i);
  if (p.b === 27 && p.c === 14 && !p.v.length) return [27, 14, range(1, 42)]; // Daniel 14:1-42, Bel and the Dragon
  if (p.b === 26 && p.c === 21 && !p.v.length) return [26, 21, range(28, 32)]; // Ezekiel 21:33-37 (LXX) = 21:28-32 (English)
  return [p.b, p.c, p.v];
}
const sets = [], index = new Map(), days = {};
for (const key of Object.keys(raw).sort()) {
  const day = raw[key];
  const set = day.sections.map(section => [section.title, section.subs.map(sub => [sub.title, sub.readings.map(reading => reading.map(fixReference))])]);
  const id = JSON.stringify(set);
  if (!index.has(id)) { index.set(id, sets.length); sets.push(set); }
  days[key] = [index.get(id), day.coptic, day.title || "", day.period || ""];
}
const keys = Object.keys(days);
const data = {source: "Coptic Orthodox Katameros via the open-source Katameros project (github.com/pierresaid/katameros-api, MIT). References only.",
  from: keys[0], to: keys.at(-1), sets, days};
fs.writeFileSync(output, `// Generated by scripts/build_katameros.mjs. Do not edit by hand.\nwindow.KATAMEROS=${JSON.stringify(data)};\n`);
console.log(`${keys.length} days (${data.from} to ${data.to}), ${sets.length} distinct reading sets, ${(fs.statSync(output).size / 1024).toFixed(0)} KB`);
